"""
題號：PY-4027
題名：座位在哪
描述：
有一架飛機左右兩側有窗戶，中間為走道，走道左兩側均有2個座位，右側有3個座位，共有20排座位，並將座位由左而右，再由前而後，依序編為1-100號，即第2排左方靠窗的座位為6號。
從鍵盤讀入1個座位號碼：該座位如果靠窗，則顯示0；如果靠走道，則顯示1；如果不靠窗也不靠走道，則顯示2。
"""

# 解答
num = int(input())
if( (num-4)%5 == 0 ):
    print(2)
elif( (num-3)%5 == 0 ):
    print(1)
elif( (num-2)%5 == 0 ):
    print(1)
elif((num-1)%5 == 0 ):
    print(0)
else:
    print(0)
