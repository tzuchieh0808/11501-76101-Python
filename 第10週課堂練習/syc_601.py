"""
題號：syc_601
題名：便當店點餐
描述：
校門口便當店的價目表請自行存成串列，依序為編號 1～6：雞腿 85、排骨 80、魚排 90、素食 70、牛肉 100、控肉 75 元。
輸入兩行：第一行便當編號 k（1～6），第二行數量 q（1～20）。總金額「滿 500 元（含）」折 50 元，輸出應付金額。
"""

# 解答
price = [85, 80, 90, 70, 100, 75]
k = int(input())
q = int(input())
total = price[k - 1] * q
if total >= 500:
    total = total - 50
print(total)
